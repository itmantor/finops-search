def build_template_workbook():
    wb = openpyxl.Workbook()

    ws = wb.active
    ws.title = "قالب"
    ws.append(INPUT_COLUMNS)
    for cell in ws[1]:
        cell.font = Font(bold=True)
    ws.append([EXAMPLE_ROW.get(c, "") for c in INPUT_COLUMNS])
    for i, col in enumerate(INPUT_COLUMNS, start=1):
        ws.column_dimensions[ws.cell(row=1, column=i).column_letter].width = max(14, len(col) + 4)

    legend = wb.create_sheet("راهنما")
    legend.append(["ستون", "الزامی/اختیاری", "توضیح"])
    for cell in legend[1]:
        cell.font = Font(bold=True)
    for row in LEGEND_ROWS:
        legend.append(list(row))
    legend.column_dimensions["A"].width = 20
    legend.column_dimensions["B"].width = 22
    legend.column_dimensions["C"].width = 90
    for row in legend.iter_rows(min_row=2):
        row[2].alignment = Alignment(wrap_text=True, vertical="top")

    buf = io.BytesIO()
    wb.save(buf)
    buf.seek(0)
    return buf
